#include <vector>
#include <unordered_set>
#include <algorithm>

using namespace std;

class SortedTriplet {
private:
    vector <int> sortedTriplet;

public:
    SortedTriplet(int n1,int n2,int n3) {
        sortedTriplet = {n1, n2, n3};
        sort(sortedTriplet.begin(), sortedTriplet.end());
    }

    // -------- getters --------

    int getN1() const  {
        return sortedTriplet[0];
    }

    int getN2() const  {
        return sortedTriplet[1];
    }

    int getN3() const  {
        return sortedTriplet[2];
    }

    vector <int> getVec() const {
        return sortedTriplet;
    }

    // -------- comparator (generated by KiroCLI) --------

    bool operator==(const SortedTriplet& other) const {
        return sortedTriplet == other.sortedTriplet;
    }
};

// -------- hash (generated by KiroCLI) -------

struct SortedTripletHash {
    size_t operator()(const SortedTriplet& t) const {
        size_t h = hash<int>()(t.getN1());
        h ^= hash<int>()(t.getN2()) + 0x9e3779b9 + (h << 6) + (h >> 2);
        h ^= hash<int>()(t.getN3()) + 0x9e3779b9 + (h << 6) + (h >> 2);
        return h;
    }
};

class Solution {
private:
    unordered_set<SortedTriplet, SortedTripletHash> find3SumSortedTriplets(vector<int>& numVec) {
        unordered_set<int> numSet(numVec.begin(), numVec.end());
        int len = numSet.size();

        unordered_set<SortedTriplet, SortedTripletHash> sortedTriplets;
        for (int i = 0; i < len; i++) {
            int valI = numVec[i];
            for (int j = i+1; j < len; j++) {
                int valJ = numVec[j];
                int valIJComplement = - (valI + valJ);
                if (numSet.find(valIJComplement) != numSet.end()) {
                    SortedTriplet sortedTriplet = SortedTriplet(valI, valJ, valIJComplement);
                    sortedTriplets.insert(sortedTriplet);
                }
            }
        }

        return sortedTriplets;
    }

    vector <vector <int> > convertToVecVec(unordered_set<SortedTriplet, SortedTripletHash>& sortedTriplets) {
        int len = sortedTriplets.size();
        vector <vector <int> > vecVec(len);

        int i = 0;
        for (auto it = sortedTriplets.begin(); it != sortedTriplets.end(); it++) {
            vecVec[i++] = (*it).getVec();
        }

        return vecVec;
    }

public:
    vector<vector<int>> threeSum(vector<int>& nums) {
        unordered_set<SortedTriplet, SortedTripletHash> sortedTriplets = find3SumSortedTriplets(nums);
        return convertToVecVec(sortedTriplets);
    }
};
